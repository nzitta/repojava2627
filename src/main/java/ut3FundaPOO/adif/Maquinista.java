package ut3FundaPOO.adif;

public class Maquinista {
	private String nombre;
	private String dni;
	private double sueldo;
	private String rango;
	
	public Maquinista(String nombre, String dni, double sueldo, String rango) {
		super();
		this.nombre = nombre;
		this.dni = dni;
		this.sueldo = sueldo;
		this.rango = rango;
	}
	
}
